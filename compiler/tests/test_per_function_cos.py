"""Per-function 4-gate precision test against golden outputs.

For each config case (seq1/2/6/32), loads golden .npz files generated by
``generate_golden_outputs.py``, calls each compiled function via ctypes in
topological SSA order, and compares every output against its golden using a
4-gate precision check.

**4 Gates:**
1.  **cos gate**: cosine similarity ≥ ``min_cos`` (default 0.9999)
2.  **zero-mean gate**: mean(|diff|) / max(mean(|expected|), 1e-8) < 0.01
3.  **outliers gate**: max(|diff|) / max(std(expected), 1e-8) < 10
4.  **top-N gate**: Jaccard overlap of top-10 indices ≥ 0.5

**Usage**::

    # Run all cases — ~64 tests (4 cases × 16 functions).  Each test's
    # class-level 120s timeout covers the class-scoped fixture (weight
    # loading + golden loading).
    pytest compiler/tests/test_per_function_cos.py -v

    # Stop at first failure (use pytest's built-in -x flag)
    pytest compiler/tests/test_per_function_cos.py -v -x

    # Filter by case or function
    pytest compiler/tests/test_per_function_cos.py -v -k "seq6"
    pytest compiler/tests/test_per_function_cos.py -v -k "main_3"

**No special treatment for seq=1** — all cases use the same 4-gate thresholds.
The config cases' fixed ``tokens`` (used to generate the goldens) are honored
by the harness, and the 4-gate check degrades gracefully for 1-element
outputs (scalar passthroughs in main_0).
"""

